create or replace function public.start_table_session(
  p_table_id uuid,
  p_customer_name text,
  p_contact_number text
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_table public.dining_tables%rowtype;
  v_session_id uuid;
begin
  select *
  into v_table
  from public.dining_tables
  where id = p_table_id
  for update;

  if not found then
    raise exception 'Table was not found.';
  end if;

  if v_table.status = 'disabled' then
    raise exception 'This table is not available.';
  end if;

  if v_table.active_session_id is not null or v_table.status = 'occupied' then
    raise exception 'This table is already occupied.';
  end if;

  insert into public.customer_sessions (table_id, customer_name, contact_number)
  values (p_table_id, nullif(trim(p_customer_name), ''), nullif(trim(p_contact_number), ''))
  returning id into v_session_id;

  update public.dining_tables
  set status = 'occupied',
      active_session_id = v_session_id
  where id = p_table_id;

  perform public.notify_admin(
    'table_occupied',
    'Table occupied',
    'Table ' || v_table.table_number || ' occupied by ' || p_customer_name || '.',
    p_table_id,
    v_session_id
  );

  return v_session_id;
end;
$$;

create or replace function public.place_order(
  p_session_id uuid,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.customer_sessions%rowtype;
  v_table public.dining_tables%rowtype;
  v_order_id uuid;
  v_line record;
  v_item public.menu_items%rowtype;
  v_offer public.offers%rowtype;
  v_offer_id uuid;
  v_quantity integer;
  v_unit_price numeric(10,2);
  v_savings numeric(10,2);
begin
  select *
  into v_session
  from public.customer_sessions
  where id = p_session_id
    and status = 'active';

  if not found then
    raise exception 'Active customer session was not found.';
  end if;

  select *
  into v_table
  from public.dining_tables
  where id = v_session.table_id;

  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Order must contain at least one item.';
  end if;

  insert into public.orders (session_id, table_id)
  values (v_session.id, v_session.table_id)
  returning id into v_order_id;

  for v_line in
    select *
    from jsonb_to_recordset(p_items)
      as x(menu_item_id uuid, quantity integer, offer_id uuid)
  loop
    v_quantity := greatest(coalesce(v_line.quantity, 1), 1);

    select *
    into v_item
    from public.menu_items
    where id = v_line.menu_item_id
      and is_available = true;

    if not found then
      raise exception 'One selected menu item is not available.';
    end if;

    v_offer_id := null;
    v_unit_price := v_item.price;
    v_savings := 0;

    if v_line.offer_id is not null then
      select *
      into v_offer
      from public.offers
      where id = v_line.offer_id
        and item_id = v_item.id
        and is_active = true
        and now() between starts_at and ends_at;

      if found then
        v_offer_id := v_offer.id;
        if v_offer.discount_type = 'percentage' then
          v_unit_price := greatest(0, round(v_item.price - (v_item.price * v_offer.discount_value / 100), 2));
        elsif v_offer.discount_type = 'fixed' then
          v_unit_price := greatest(0, round(v_item.price - v_offer.discount_value, 2));
        else
          v_unit_price := greatest(0, round(v_offer.discount_value, 2));
        end if;
        v_savings := greatest(0, v_item.price - v_unit_price);
      end if;
    end if;

    insert into public.order_items (
      order_id,
      menu_item_id,
      offer_id,
      item_name,
      unit_price,
      original_unit_price,
      quantity,
      line_total,
      savings_total
    )
    values (
      v_order_id,
      v_item.id,
      v_offer_id,
      v_item.name,
      v_unit_price,
      v_item.price,
      v_quantity,
      round(v_unit_price * v_quantity, 2),
      round(v_savings * v_quantity, 2)
    );
  end loop;

  perform public.recalculate_order_total(v_order_id);

  perform public.notify_admin(
    'order_placed',
    'New order placed',
    'Table ' || v_table.table_number || ' ordered. Customer: ' || v_session.customer_name || '.',
    v_table.id,
    v_session.id,
    v_order_id
  );

  return v_order_id;
end;
$$;

