create or replace function public.request_order_change(
  p_session_id uuid,
  p_order_item_id uuid,
  p_request_type text,
  p_requested_quantity integer default null,
  p_reason text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.customer_sessions%rowtype;
  v_order public.orders%rowtype;
  v_item public.order_items%rowtype;
  v_table public.dining_tables%rowtype;
  v_request_id uuid;
begin
  if p_request_type not in ('cancel', 'update_quantity') then
    raise exception 'Invalid request type.';
  end if;

  if p_request_type = 'update_quantity' and coalesce(p_requested_quantity, 0) < 1 then
    raise exception 'Requested quantity must be at least 1.';
  end if;

  select *
  into v_session
  from public.customer_sessions
  where id = p_session_id
    and status = 'active';

  if not found then
    raise exception 'Active customer session was not found.';
  end if;

  select oi.*
  into v_item
  from public.order_items oi
  join public.orders o on o.id = oi.order_id
  where oi.id = p_order_item_id
    and o.session_id = v_session.id
    and oi.status not in ('cancelled', 'change_pending', 'cancel_pending')
  for update;

  if not found then
    raise exception 'Order item cannot be changed right now.';
  end if;

  if exists (
    select 1
    from public.order_change_requests
    where order_item_id = p_order_item_id
      and status = 'pending'
  ) then
    raise exception 'A request for this item is already pending.';
  end if;

  select * into v_order from public.orders where id = v_item.order_id;
  select * into v_table from public.dining_tables where id = v_order.table_id;

  insert into public.order_change_requests (
    session_id,
    order_item_id,
    request_type,
    requested_quantity,
    reason
  )
  values (
    v_session.id,
    v_item.id,
    p_request_type,
    p_requested_quantity,
    p_reason
  )
  returning id into v_request_id;

  update public.order_items
  set status = case
    when p_request_type = 'cancel' then 'cancel_pending'
    else 'change_pending'
  end
  where id = v_item.id;

  perform public.notify_admin(
    'change_request',
    'Order change requested',
    'Table ' || v_table.table_number || ' requested ' || replace(p_request_type, '_', ' ') || ' for ' || v_item.item_name || '.',
    v_table.id,
    v_session.id,
    v_order.id,
    null,
    v_request_id
  );

  return v_request_id;
end;
$$;

create or replace function public.get_customer_session_summary(p_session_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.customer_sessions%rowtype;
  v_table public.dining_tables%rowtype;
  v_settings public.restaurant_settings%rowtype;
  v_orders jsonb;
  v_requests jsonb;
  v_calls jsonb;
  v_due numeric(10,2);
  v_saved numeric(10,2);
begin
  select *
  into v_session
  from public.customer_sessions
  where id = p_session_id;

  if not found then
    raise exception 'Customer session was not found.';
  end if;

  select * into v_table from public.dining_tables where id = v_session.table_id;
  select * into v_settings from public.restaurant_settings where singleton = true;

  select coalesce(jsonb_agg(
    to_jsonb(o) || jsonb_build_object(
      'items',
      coalesce((
        select jsonb_agg(to_jsonb(oi) order by oi.created_at asc)
        from public.order_items oi
        where oi.order_id = o.id
      ), '[]'::jsonb)
    )
    order by o.created_at desc
  ), '[]'::jsonb)
  into v_orders
  from public.orders o
  where o.session_id = v_session.id;

  select coalesce(jsonb_agg(to_jsonb(r) order by r.created_at desc), '[]'::jsonb)
  into v_requests
  from public.order_change_requests r
  where r.session_id = v_session.id;

  select coalesce(jsonb_agg(to_jsonb(c) order by c.created_at desc), '[]'::jsonb)
  into v_calls
  from public.staff_calls c
  where c.session_id = v_session.id;

  select
    coalesce(sum(oi.line_total) filter (where oi.status <> 'cancelled'), 0),
    coalesce(sum(oi.savings_total) filter (where oi.status <> 'cancelled'), 0)
  into v_due, v_saved
  from public.order_items oi
  join public.orders o on o.id = oi.order_id
  where o.session_id = v_session.id;

  return jsonb_build_object(
    'session', to_jsonb(v_session),
    'table', to_jsonb(v_table),
    'orders', v_orders,
    'change_requests', v_requests,
    'staff_calls', v_calls,
    'settings', to_jsonb(v_settings),
    'totals', jsonb_build_object(
      'due', v_due,
      'saved', v_saved
    )
  );
end;
$$;

create or replace function public.admin_approve_change_request(
  p_request_id uuid,
  p_admin_note text default 'Approved by admin.'
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.order_change_requests%rowtype;
  v_item public.order_items%rowtype;
  v_order_id uuid;
  v_session public.customer_sessions%rowtype;
  v_table public.dining_tables%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Admin access required.';
  end if;

  select *
  into v_request
  from public.order_change_requests
  where id = p_request_id
  for update;

  if not found or v_request.status <> 'pending' then
    raise exception 'Request is not pending.';
  end if;

  select *
  into v_item
  from public.order_items
  where id = v_request.order_item_id
  for update;

  v_order_id := v_item.order_id;

  if v_request.request_type = 'cancel' then
    update public.order_items
    set status = 'cancelled',
        quantity = 0,
        line_total = 0,
        savings_total = 0
    where id = v_item.id;
  else
    update public.order_items
    set status = 'placed',
        quantity = v_request.requested_quantity,
        line_total = round(unit_price * v_request.requested_quantity, 2),
        savings_total = round(greatest(0, original_unit_price - unit_price) * v_request.requested_quantity, 2)
    where id = v_item.id;
  end if;

  update public.order_change_requests
  set status = 'approved',
      admin_note = coalesce(nullif(trim(p_admin_note), ''), 'Approved by admin.'),
      resolved_by = auth.uid(),
      resolved_at = now()
  where id = v_request.id;

  perform public.recalculate_order_total(v_order_id);

  select s.* into v_session
  from public.customer_sessions s
  join public.orders o on o.session_id = s.id
  where o.id = v_order_id;

  select * into v_table from public.dining_tables where id = v_session.table_id;

  perform public.notify_admin(
    'change_approved',
    'Request approved',
    'Table ' || v_table.table_number || ' request approved for ' || v_item.item_name || '.',
    v_table.id,
    v_session.id,
    v_order_id,
    null,
    v_request.id
  );

  return v_request.id;
end;
$$;

create or replace function public.admin_reject_change_request(
  p_request_id uuid,
  p_admin_note text default 'Rejected because the order is already being prepared.'
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.order_change_requests%rowtype;
  v_item public.order_items%rowtype;
  v_order_id uuid;
  v_session public.customer_sessions%rowtype;
  v_table public.dining_tables%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Admin access required.';
  end if;

  select *
  into v_request
  from public.order_change_requests
  where id = p_request_id
  for update;

  if not found or v_request.status <> 'pending' then
    raise exception 'Request is not pending.';
  end if;

  select *
  into v_item
  from public.order_items
  where id = v_request.order_item_id
  for update;

  v_order_id := v_item.order_id;

  update public.order_items
  set status = 'placed'
  where id = v_item.id;

  update public.order_change_requests
  set status = 'rejected',
      admin_note = coalesce(nullif(trim(p_admin_note), ''), 'Rejected because the order is already being prepared.'),
      resolved_by = auth.uid(),
      resolved_at = now()
  where id = v_request.id;

  perform public.recalculate_order_total(v_order_id);

  select s.* into v_session
  from public.customer_sessions s
  join public.orders o on o.session_id = s.id
  where o.id = v_order_id;

  select * into v_table from public.dining_tables where id = v_session.table_id;

  perform public.notify_admin(
    'change_rejected',
    'Request rejected',
    'Table ' || v_table.table_number || ' request rejected for ' || v_item.item_name || '.',
    v_table.id,
    v_session.id,
    v_order_id,
    null,
    v_request.id
  );

  return v_request.id;
end;
$$;

create or replace function public.admin_close_paid_session(p_session_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_session public.customer_sessions%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Admin access required.';
  end if;

  select *
  into v_session
  from public.customer_sessions
  where id = p_session_id
  for update;

  if not found then
    raise exception 'Session was not found.';
  end if;

  update public.customer_sessions
  set status = 'paid',
      paid_at = coalesce(paid_at, now()),
      closed_at = now()
  where id = v_session.id;

  update public.dining_tables
  set status = 'available',
      active_session_id = null
  where id = v_session.table_id
    and active_session_id = v_session.id;

  perform public.notify_admin(
    'bill_paid',
    'Bill paid',
    'A bill was marked paid and the table was released.',
    v_session.table_id,
    v_session.id
  );

  return v_session.id;
end;
$$;

